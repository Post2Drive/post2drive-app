import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const eligibility = read("../../lib/eligibility.ts");
const jobs = read("../../app/api/jobs/route.ts");
const bid = read("../../app/api/jobs/[id]/bid/route.ts");
const accept = read("../../app/api/jobs/[id]/accept/route.ts");
const award = read("../../app/api/jobs/[id]/bids/[bidId]/accept/route.ts");
const opportunities = read("../../lib/opportunities.ts");
assert.ok(eligibility.includes("export function vehicleEligibilityWhere"));
assert.ok(eligibility.includes('verificationStatus: "verified"'));
assert.ok(eligibility.includes("insuranceValidUntil: { gte: dateCutoff }"));
assert.ok(eligibility.includes("profile?.inspectionRequiredAtCountryLevel"));
assert.ok(eligibility.includes("export async function getEligibleVehicleTypes"));
assert.ok(eligibility.includes("export async function hasEligibleVehicleForJob"));
assert.ok(eligibility.includes("export function canPostJobs"));
assert.ok(jobs.includes("getEligibleVehicleTypes"));
assert.ok(jobs.includes("vehicleType: { in: eligibleFeedVehicleTypes }"));
assert.ok(jobs.includes("canPostJobs(account)"));
assert.ok(bid.includes("hasEligibleVehicleForJob"));
assert.ok(accept.includes("hasEligibleVehicleForJob"));
assert.ok(award.includes("vehicleEligibilityWhere"));
assert.ok(!bid.includes('companyVerificationStatus !== "verified"'));
assert.ok(!accept.includes('companyVerificationStatus !== "verified"'));
assert.ok(!opportunities.includes('driver.companyVerificationStatus !== "verified"'));
assert.ok(award.includes("canPostJobs(posterVerification)"));
assert.ok(award.includes("BID_NO_LONGER_ELIGIBLE"));
assert.ok(jobs.includes("qaTestAccounts: { none: {} }"), "keep QA-account exclusion database-side");
console.log("Unified verification and vehicle-eligibility contract passed.");
