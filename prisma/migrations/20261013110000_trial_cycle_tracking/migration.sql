  "id" TEXT NOT NULL,
  "accountId" TEXT NOT NULL,
  "cycleNumber" INTEGER NOT NULL,
  "startAt" TIMESTAMP(3) NOT NULL,
  "endAt" TIMESTAMP(3) NOT NULL,
  "graceStartedAt" TIMESTAMP(3),
  "graceEndsAt" TIMESTAMP(3),
  "status" TEXT NOT NULL DEFAULT 'active',
