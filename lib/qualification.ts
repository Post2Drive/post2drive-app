import { prisma } from "@/lib/prisma";
import {
  evaluateDriverFairness,
  calculatePosterFairPostedTarget,
  POSTER_NORMAL_COMPLETED_TARGET,
  POSTER_NORMAL_POSTED_TARGET,
  type QualificationWindow,
} from "@/lib/fairness";
import { isUkAccount } from "@/lib/uk";

export const GRACE_RATIO = 2 / 3;

export async function getPosterQualification(
  accountId: string,
  window?: QualificationWindow
) {
  const account =
    await prisma.account.findUnique({
      where: {
        id: accountId,
      },
      select: {
        country: true,
        currency: true,
      },
    });

  if (
    !account ||
    !isUkAccount(account)
  ) {
    return {
      ukEligible: false,
      postedJobs: 0,
      completedJobs: 0,
      normalPostedTarget:
        POSTER_NORMAL_POSTED_TARGET,
      adjustedPostedTarget: 0,
      completedTarget:
        POSTER_NORMAL_COMPLETED_TARGET,
      postedQualified: false,
      completedQualified: false,
      qualified: false,
      graceEligible: false,
      fairnessRatio: 0,
    };
  }

  const [
    postedJobs,
    completedJobs,
  ] = await Promise.all([
    prisma.job.count({
      where: {
        posterId: accountId,
        ...(window
          ? { createdAt: { gte: window.startAt, lte: window.endAt } }
          : {}),
      },
    }),

    prisma.job.count({
      where: {
        posterId: accountId,
        status: "completed",
        ...(window
          ? {
              activities: {
                some: {
                  action: "DELIVERY_CONFIRMED",
                  toStatus: "completed",
                  createdAt: { gte: window.startAt, lte: window.endAt },
                },
              },
            }
          : {}),
      },
    }),
  ]);

  /*
   * DriverOpportunity records represent genuine
   * supply-side exposure generated by the platform.
   *
   * We use the number of the poster's jobs that
   * received marketplace opportunities as the
   * temporary fair-capacity evidence.
   */
  const opportunityJobs =
    await prisma.driverOpportunity.groupBy(
      {
        by: ["jobId"],

        where: {
          job: {
            posterId: accountId,
            ...(window
              ? { createdAt: { gte: window.startAt, lte: window.endAt } }
              : {}),
          },
          ...(window
            ? { exposedAt: { gte: window.startAt, lte: window.endAt } }
            : {}),
        },
      }
    );

  const fairPosted =
    calculatePosterFairPostedTarget(
      opportunityJobs.length
    );

  const postedQualified =
    postedJobs >=
    fairPosted.adjustedTarget;

  const completedQualified =
    completedJobs >=
    POSTER_NORMAL_COMPLETED_TARGET;

  const normalCompleteRatio =
    completedJobs /
    POSTER_NORMAL_COMPLETED_TARGET;

  const normalPostedRatio =
    postedJobs /
    POSTER_NORMAL_POSTED_TARGET;

  const graceEligible =
    normalPostedRatio >=
      GRACE_RATIO &&
    normalCompleteRatio >=
      GRACE_RATIO;

  return {
    ukEligible: true,

    postedJobs,

    completedJobs,

    normalPostedTarget:
      POSTER_NORMAL_POSTED_TARGET,

    adjustedPostedTarget:
      fairPosted.adjustedTarget,

    completedTarget:
      POSTER_NORMAL_COMPLETED_TARGET,

    postedQualified,

    completedQualified,

    qualified:
      postedQualified &&
      completedQualified,

    graceEligible,

    fairnessRatio:
      fairPosted.fairnessRatio,
  };
}

export async function getDriverQualification(
  accountId: string,
  window?: QualificationWindow
) {
  return evaluateDriverFairness(accountId, window);
}

export async function saveDriverQualificationSnapshot(
  accountId: string,
  cycleNumber: number,
  window?: QualificationWindow
) {
  const result =
    await getDriverQualification(accountId, window);

  if (!result.ukEligible) {
    return null;
  }

  return prisma.qualificationSnapshot.create({
    data: {
      accountId,

      side:
        "driver",

      cycleNumber,

      normalTarget:
        result.normalTarget,

      adjustedTarget:
        result.adjustedTarget,

      actualAmount:
        result.actualCompletedJobs,

      fairnessRatio:
        result.fairnessRatio,

      opportunitiesAvailable:
        result.suitableOpportunities,

      opportunitiesRequired:
        result.normalTarget,

      qualified:
        result.qualified,

      explanation:
        `UK qualification: driver had ${result.suitableOpportunities} suitable marketplace opportunities against a normal target of ${result.normalTarget}. Fairness-adjusted target was ${result.adjustedTarget}. Actual completed jobs: ${result.actualCompletedJobs}.`,
    },
  });
}